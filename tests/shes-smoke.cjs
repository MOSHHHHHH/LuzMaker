#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const source=fs.readFileSync("scripts/shes.js","utf8");
const scope=vm.createContext({Math,Number,Array,Set,JSON});
vm.runInContext(source,scope);
const run=code=>vm.runInContext(code,scope);
const near=(a,b,tol=.0005)=>assert(Math.abs(a-b)<tol, a+" != "+b);
let uniform=run("SHES.analyze([0,30,60,90,120])");
assert.equal(uniform.status,"ok");
near(uniform.SHES,100);near(uniform.SHES_T,100);near(uniform.randomArrivalWait,15);
let clustered=run("SHES.analyze([0,5,60,65,120])");
near(clustered.SHES,100*120*120/(4*(25+3025+25+3025)));
near(clustered.randomArrivalWait,6100/240);
assert(clustered.SHES_T>=clustered.SHES);
let uneven=run("SHES.analyze([0,20,60,80,120])");
near(uneven.SHES,90);near(uneven.randomArrivalWait,2000/120);
let shifted=run("SHES.analyze([100,130,160,190,220])");
near(shifted.SHES,100);
assert.equal(run("SHES.analyze([10,20]).status"),"insufficient");
assert.equal(run("SHES.analyze([10,10,10]).status"),"zero_span");
const combined=run("SHES.analyze([0,15,30,45,60])");
near(combined.SHES,100);
assert.equal(combined.departures,5);
const withDuplicate=run("SHES.analyze([0,0,30,60])");
assert.equal(withDuplicate.departures,4,"Distinct simultaneous services must be retained");
assert(withDuplicate.SHES<100);
assert(uneven.sensitivity.min<=uneven.SHES_T+0.001);
assert(uneven.sensitivity.max>=uneven.SHES_T-0.001);
const html=fs.readFileSync("index.html","utf8");
assert(html.includes('shes=1'),"Experiment must be gated by query parameter");
assert(html.includes("כל הקווים שנבחרו יחד"),"Combined timetable explanation must be visible");
assert(html.includes("תחנות סמוכות ולא זהות"),"Nearby stops must be allowed");
assert(html.includes("אותו מוצא ויעד"),"Substitutability limitation must be explicit");
assert(html.includes('row.min'),"Combined departure times must use stop arrivals");
console.log("PASS: SHES math, duplicates, missing data, sensitivity, opt-in, parallel lines");
